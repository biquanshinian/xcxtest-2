/**
 * 管理后台自动登录：拉验证码 → 解析 SVG 字符 → 登录 → 写 .cursor/oa-admin.local.env
 * 用法：
 *   node scripts/ops-admin-login.js --user admin --pass '***'
 * 或环境变量 OA_ADMIN_USER / OA_ADMIN_PASS
 *
 * 勿把密码提交进仓库；仅写入已 gitignore 的本地 env。
 */
const fs = require('fs')
const path = require('path')
const http = require('http')
const https = require('https')

const ROOT = path.resolve(__dirname, '..')
const ENV_PATH = path.join(ROOT, '.cursor', 'oa-admin.local.env')
const DEFAULT_API =
  'https://cloud1-9gdqgdt5bfaa20fb-1397421562.ap-shanghai.app.tcloudbase.com/admin'

function arg(name, fallback = '') {
  const i = process.argv.indexOf(name)
  if (i >= 0 && process.argv[i + 1]) return process.argv[i + 1]
  return fallback
}

function requestJson(url, { method = 'POST', body } = {}) {
  return new Promise((resolve, reject) => {
    const u = new URL(url)
    const lib = u.protocol === 'https:' ? https : http
    const payload = body == null ? null : Buffer.from(JSON.stringify(body))
    const req = lib.request(
      {
        hostname: u.hostname,
        port: u.port || (u.protocol === 'https:' ? 443 : 80),
        path: u.pathname + u.search,
        method,
        headers: {
          'Content-Type': 'application/json',
          ...(payload ? { 'Content-Length': payload.length } : {})
        }
      },
      (res) => {
        const chunks = []
        res.on('data', (c) => chunks.push(c))
        res.on('end', () => {
          const text = Buffer.concat(chunks).toString('utf8')
          let json = null
          try {
            json = JSON.parse(text)
          } catch (e) {
            return reject(new Error(`非 JSON HTTP ${res.statusCode}: ${text.slice(0, 200)}`))
          }
          resolve({ status: res.statusCode, json })
        })
      }
    )
    req.on('error', reject)
    if (payload) req.write(payload)
    req.end()
  })
}

function callAdmin(base, apiPath, body, method = 'POST') {
  return requestJson(base, {
    method: 'POST',
    body: {
      path: apiPath,
      method,
      query: {},
      body: body || {},
      headers: {}
    }
  })
}

function extractCaptchaFromSvgDataUrl(dataUrl) {
  const m = String(dataUrl || '').match(/^data:image\/svg\+xml;base64,(.+)$/i)
  if (!m) throw new Error('验证码不是 svg+base64')
  const svg = Buffer.from(m[1], 'base64').toString('utf8')
  const chars = []
  const re = /<text\b[^>]*>([^<]*)<\/text>/gi
  let hit
  while ((hit = re.exec(svg))) {
    const ch = String(hit[1] || '')
      .replace(/&lt;/g, '<')
      .replace(/&gt;/g, '>')
      .replace(/&amp;/g, '&')
      .replace(/&apos;/g, "'")
      .replace(/&quot;/g, '"')
      .trim()
    if (ch) chars.push(ch)
  }
  const code = chars.join('').toUpperCase()
  if (code.length < 4) throw new Error(`解析验证码失败: ${code || '(empty)'}`)
  return code
}

function writeEnv({ base, token, user }) {
  const lines = [
    `# auto-generated by scripts/ops-admin-login.js — DO NOT COMMIT`,
    `ADMIN_API_BASE=${base}`,
    `OA_ADMIN_TOKEN=${token}`,
    `OA_ADMIN_USER=${user}`,
    `OA_ADMIN_TOKEN_AT=${new Date().toISOString()}`
  ]
  fs.mkdirSync(path.dirname(ENV_PATH), { recursive: true })
  fs.writeFileSync(ENV_PATH, lines.join('\n') + '\n', 'utf8')
}

async function main() {
  const base = (process.env.ADMIN_API_BASE || DEFAULT_API).replace(/\/$/, '')
  const username =
    arg('--user', process.env.OA_ADMIN_USER || process.env.ADMIN_USERNAME || 'admin').trim()
  const password = arg('--pass', process.env.OA_ADMIN_PASS || process.env.ADMIN_PASSWORD || '')
  if (!password) {
    console.error('缺少密码：--pass 或 OA_ADMIN_PASS')
    process.exit(1)
  }

  const capRes = await callAdmin(base, '/auth/captcha', {}, 'GET')
  const cap = (capRes.json && (capRes.json.data || capRes.json)) || {}
  if (capRes.json && capRes.json.code && capRes.json.code !== 0) {
    throw new Error(capRes.json.message || '获取验证码失败')
  }
  const captchaId = cap.captchaId
  const captchaCode = extractCaptchaFromSvgDataUrl(cap.svg)
  console.log('captcha ok', captchaId.slice(0, 8) + '…', 'len', captchaCode.length)

  const loginRes = await callAdmin(base, '/auth/login', {
    username,
    password,
    captchaId,
    captchaCode
  })
  const j = loginRes.json || {}
  if (j.code && j.code !== 0) {
    console.error('LOGIN_FAIL', j.code, j.message)
    process.exit(1)
  }
  const data = j.data || j
  const token = data.token
  if (!token) {
    console.error('LOGIN_FAIL no token', JSON.stringify(j).slice(0, 300))
    process.exit(1)
  }
  writeEnv({ base, token, user: username })
  console.log('LOGIN_OK', {
    user: (data.user && data.user.username) || username,
    role: data.user && data.user.role,
    env: ENV_PATH
  })
}

main().catch((e) => {
  console.error('ERR', e.message || e)
  process.exit(1)
})
